; AltROMs subsyscg.rom — FM77AV CG (キャラクタジェネレータ) ROM
;
; 8192 byte 固定。サブ CPU 側の $D800-$DFFF (2KB) に出る ROM で、どの 2KB を出すかは
; サブシステム I/O レジスタ $D430 の bit1・bit0 で選ぶ (参考書籍):
;   00 = カタカナ / 01 = ひらがな / 10 = サブモニタ ROM 1 / 11 = サブモニタ ROM 2。
; 主用途は 8x8 ANK フォントデータ供給 (= データ ROM)。
; リセットベクタは持たない (= このバンクは実行起点にならない)。
;
; 独自 8x8 ANK フォント (scripts/genfont.py 生成) を 4 バンク分
; ($0000/$0800/$1000/$1800 = $D430 bit1・bit0 の 00 / 01 / 10 / 11) に配置する。
; 実行コードは持たない (データのみ)。
;
; フォント書体は公開当時の慣行に倣う独自ビットマップ。
;==============================================================================

                ORG     $0000

;------------------------------------------------------------------------------
; バンク 0-3: 8x8 ANK フォント (各 2KB)。
;   genfont.py が 2KB (256 文字 × 8 byte) を出力。$D800-$DFFF に出る 2KB は $D430 の
;   bit1・bit0 で 4 つから選ばれるため、同一フォントを全 4 バンクに配置して
;   どれが選ばれても同じ字形が出るようにする。
;------------------------------------------------------------------------------
cg_bank0:       INCLUDEBIN "../build/font.bin"
                ZMB     $0800-*         ; バンク 0 を 2KB 境界まで埋める
cg_bank1:       INCLUDEBIN "../build/font.bin"
                ZMB     $1000-*
cg_bank2:       INCLUDEBIN "../build/font.bin"
                ZMB     $1800-*
cg_bank3:       INCLUDEBIN "../build/font.bin"
                ZMB     $2000-*         ; 全体を 8192 byte に揃える
