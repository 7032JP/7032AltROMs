; AltROMs initav1.rom — FM77AV 第 1 世代 メイン CPU イニシエート ROM
;
; 8192 byte 固定。initiate.rom / initbase.rom と同じメイン CPU イニシエート ROM
; だが、**起動機構そのものが異なる世代** 向けの変種である。
;
; 外部から観察できる挙動 (動作観察) が示す世代差:
;   第 1 世代 : 起動用 ROM イメージを resident boot 領域へ複写し **その場で実行** する。
;               AV ブートイメージ (ROM file offset $1C00 / 転送先 $5000) の機構を
;               そもそも備えない。
;   中位/上位 : 起動用 ROM イメージは **複写のみ** を行い、別途 AV ブートイメージを
;               $5000 へ転送してそちらへ引渡す。
;   FM 音源初期化とアナログパレット初期化は **全世代で実施** される。CRTC 初期化は
;   上位世代のみ必要な処理 (当実装はもともと CRTC を操作しないので差は生じない)。
;
; 本変種の構成差 (initiate.rom との差):
;   1. AV ブートイメージを持たない (file offset $1C00 は空き)。
;   2. AV ブートイメージの転送処理と、その固定バイトパターン (転送分岐 BRA /
;      引渡し JMP) を持たない。
;   3. トランポリンの引渡し先が resident boot ($FE00) 直行。
;   4. 機種識別域の世代名が "AV001"、機種区分は非提示 ($FF x 6)。
;
; 実体は initiate/initiate.s を INIT_AV1 条件でアセンブルしたものであり、
; ソースは一本しか持たない。
;
; 配置先のファイル名は他の変種と同じ initiate.rom である (実行環境はこの名で
; 読む)。どの変種を配るかは、ビルドで生成した変種のうち 1 つを配置先へ
; initiate.rom という名前で置くことで選ぶ。
;==============================================================================

