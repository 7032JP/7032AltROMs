; tc01_03 — $01 の単色表示 GR: GR≠0 のとき文字はグリーンだけで表示される
;   $D38A=GR 単色表示。$0D で文字色を赤 (2) に定めてから $03 で "A" を 1 文字出す。
;   GR=1 なので画面に出る画素は緑 (4) だけになり、赤 (2) の画素は 1 つも無い。
;   80 桁のとき 1 文字は 8x8 画素なので、先頭の桁は (0,0)-(7,7) に当たる。
; 準備: カーソルの点滅を止める ($0C・下位ビット 0)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$02,$0C,$00
        FCB     $00,$09,$01,$00,$50,$19,$00,$19,$00,$01,$01
        FCB     $00,$04,$0D,$00,$00,$02
        FCB     $00,$03,$03,$01,$41

OBSTAB:
        FCB     OP_ANYC,4
        FDB     0,0,7,7                 ; 先頭の桁に緑 (4) の点がある
        FCB     OP_CNT,2
        FDB     0,0,7,7                 ; 赤 (2) の画素は無い
        FCB     OP_END
        END
