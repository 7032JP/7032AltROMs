; tc19_02 — $19 SYMBOL のファンクションコード F = 5 (NOT)
;   F = 5 (NOT) は字形のビットを反転して描く。等倍 (W = H = 1) で "A" を (100,100) に NOT で描くと、
;   字形のドットが立っていない画素が描かれ、字形のドットの位置は描かれない。
;   字形に依存しないよう、隣の (108,100) に同じ "A" を通常
;   (F = 0) で描き、2 つの 8 x 8 の枠 (100,100)-(115,107) の非黒画素を数える。
;   NOT の字と通常の字は互いに補い合うので、字形によらず 64 になる。
; 準備: カーソルの点滅を止め ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $00,$0C,$19,$07,$05,$00,$01,$01,$00,$64,$00,$64
        FCB     $01,$41
        FCB     $00,$0C,$19,$07,$00,$00,$01,$01,$00,$6C,$00,$64
        FCB     $01,$41

OBSTAB:
        FCB     OP_LIT
        FDB     100,100,115,107         ; NOT の "A" と通常の "A" の 16x8: 合わせて 64
        FCB     OP_ANY
        FDB     100,100,107,107         ; NOT の "A" の 8x8 に点がある
        FCB     OP_ANY
        FDB     108,100,115,107         ; 通常の "A" の 8x8 に点がある
        FCB     OP_LIT
        FDB     0,0,639,99              ; 上: 何も出ない
        FCB     OP_LIT
        FDB     0,108,639,199           ; 下: 何も出ない
        FCB     OP_LIT
        FDB     0,100,99,107            ; 左: 何も出ない
        FCB     OP_LIT
        FDB     116,100,639,107         ; 右: 何も出ない
        FCB     OP_END
        END
