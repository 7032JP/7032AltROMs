; tc03_06 — BS (Back Space) オーダ $08 のフィールド境界 (参考書籍)。
;   BS は「現在のバッファアドレスが、フィールドの先頭でないならば、バッファ
;   アドレスを 1 つ前に戻します。フィールドの先頭の場合は、何も動作しません」。
;   境界は桁の先頭ではなくフィールドの先頭なので、
;     (1) 桁 4 から始まるフィールドに A B を置いて BS を 4 回出しても、
;         バッファアドレスは桁 4 で止まる (桁 3 以前へは戻らない)
;     (2) 同じフィールドの中なら行をまたいで戻る (桁 0・行 1 から BS を 1 回出すと
;         桁 39・行 0 へ戻る)
;   バッファアドレスは $0A (Get Buffer Address、参考書籍) で読み戻す。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$0D,$03,$0B
        FCB     $12,$04,$00
        FCB     $11,$07,$41,$42
        FCB     $08,$08,$08,$08
        FCB     $02,$01,$0A
        FCB     $00,$06,$03,$04
        FCB     $12,$00,$01,$08
        FCB     $02,$01,$0A

OBSTAB:
        FCB     OP_END
        END
