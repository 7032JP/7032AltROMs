; tc3d_01 — $3D タイマ設定 → $3E タイマ読出し
;   $3D: $D383=ビットマスク, $D384=フラグ値, $D385〜=4 byte フィールド群
;        (マスク bit0=フラグ値, bit1〜bit4=4 byte 群を 1 つずつ選ぶ)
;   $3E: $D384〜 に 17 byte のタイマ作業域を返す
;   $3D を 2 回発行し、1 回目でフラグ値と時刻の欄を、2 回目は時刻の欄だけを
;   置き換える。2 回目はマスクからフラグ値を外し、フラグ値の欄には別の値
;   ($FF) を置くので、応答のフラグ値が 1 回目の $01 のままなら「マスクで
;   選んでいない欄は書き換わらない」ことも同時に確かめられる。
;   照合対象は応答の先頭 5 byte (パラメータ欄の頭 + フラグ値 + 時・分・秒)
;   に絞る。時刻の最下位桁 (1/50 秒) はサブ CPU の周期処理が刻々と進めるため、
;   コマンド 2 件の間隔しか離れていなくても値が定まらない。秒の桁が動くのは
;   最下位桁を 0 に置いてから 50 ティック (1 秒) 後なので、この 5 byte は
;   実行の速さに左右されない。
; 準備: カーソルの点滅を止め ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     5
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $00,$07,$3D,$03,$01,$12,$22,$33,$00
        FCB     $00,$07,$3D,$02,$FF,$13,$24,$35,$00
        FCB     $05,$01,$3E

OBSTAB:
        FCB     OP_LIT
        FDB     0,0,639,199
        FCB     OP_END
        END
