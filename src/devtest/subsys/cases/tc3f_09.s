; tc3f_09 — $3F バイトコード: サブ側のワーク。
;   $D03B は 1 行のバイト数、$D40E は表示開始位置 (I/O) である。
;   $D01F (表示開始位置の控え) の中身はそれまでの画面操作で変わるので、本試験は
;   控えを読まず、1 行のバイト数を直接 $D40E へ入れて 1 行ぶん下へずらす。
;
;     CE ... ではなく次の 19 バイト (展開先 $D3C0):
;       FC D0 3B   LDD  $D03B     1 行のバイト数
;       FD D4 0E   STD  $D40E     表示開始位置 (I/O) を動かす = 画面が縦にずれる
;       1F 01      TFR  D,X
;       B6 D4 09   LDA  $D409     VRAM ゲート ON (読出しで開く)
;       C6 FF      LDB  #$FF
;       E7 84      STB  ,X        新しい表示開始位置の先頭 8 画素を B 面に灯す
;       F7 D4 09   STB  $D409     ゲート OFF (書込みで閉じる)
;       39         RTS
;
;   1 行のバイト数が 40 桁 20 行の 1 行 (800 バイト) であれば、印は縦 10 画素の
;   位置に出る。640 画素幅の 1 ラスタが 80 バイトなので、8 ライン ぶん (640 バイト)
;   なら縦 8 画素、2 行ぶん (1600 バイト) なら縦 20 画素の位置になる。この 3 点を
;   画素の有無 (OP_ANY) で見分ける。印の画素の数は $FF の書込み 1 回ぶんに限られ
;   ないので、数ではなく有無で見る。
; 準備: カーソルの点滅を止め ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     3
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $00,$27,$3F,$00,$00,$00,$00,$00,$00,$00,$00,$91
        FCB     $D3,$96,$D3,$C0,$00,$13,$93,$D3,$C0,$90,$FC,$D0
        FCB     $3B,$FD,$D4,$0E,$1F,$01,$B6,$D4,$09,$C6,$FF,$E7
        FCB     $84,$F7,$D4,$09,$39

OBSTAB:
        FCB     OP_ANY
        FDB     0,10,7,10
        FCB     OP_ANYC,1                       ; 印は B 面 (色番号 bit0)
        FDB     0,10,7,10
        FCB     OP_ANY
        FDB     0,8,7,8
        FCB     OP_ANY
        FDB     0,20,7,20
        FCB     OP_ANY
        FDB     0,0,7,0
        FCB     OP_END
        END
