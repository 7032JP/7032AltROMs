; tc08_02 — $08 文字ブロック読出し 形式 2: アトリビュート文字のフィールドの先頭 (F、最上位ビット)
;   コンソール出力 ($03) で "ABC" を書いてから SF オーダ ($11 05) を挟み、続けて 'D' を
;   書く。SF を置いたセル ('D') がフィールドの先頭 (F=1) になり、その属性は 5。
;   "ABC" のセルは消去時の属性 7 のまま。ただし画面の先頭のセル ("A") は消去で
;   F が立つので、属性は $87 で返る。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$05,$03,$03,$41,$42,$43
        FCB     $00,$04,$03,$02,$11,$05
        FCB     $00,$03,$03,$01,$44
        FCB     $FF,$05,$08,$00,$00,$03,$00

OBSTAB:
        FCB     OP_ANYC,7
        FDB     0,0,47,9                ; "ABC" は属性 7
        FCB     OP_CNT,5
        FDB     0,0,47,9                ; "ABC" に色 5 は無い
        FCB     OP_ANYC,5
        FDB     48,0,63,9               ; "D" は属性 5
        FCB     OP_CNT,7
        FDB     48,0,63,9               ; "D" に色 7 は無い
        FCB     OP_LIT
        FDB     64,0,639,9              ; 同じ行の残り: 何も出ない
        FCB     OP_LIT
        FDB     0,10,639,199            ; 2 行目以降: 何も出ない
        FCB     OP_END
        END
