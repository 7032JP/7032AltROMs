; tcbas_10 — GET@ で読んだ 64x64 の図形を PUT@ で書き戻す: 1 面 512 バイトの
;   パターンは PUT BLOCK 1 の 1 回に入り切らないので、継続フラグ 1 で送り、残りを
;   継続コマンド ($64) で送る。最後の行まで元と同じ点が描かれる
; BASIC の描画文で画面を作り、その結果をこのサンプル自身が読み戻して報告します。
; 先頭の `@bas` 行が、機械語を読み込んだあとに走らせる BASIC の行です。
;
;   元 (100,100)-(163,163): 枠、対角線、塗り潰し矩形 (108,140)-(155,159) を色 7 で描く (点は 1258 個)。
;   写し先 (300,100)-(363,163) は先に色 3 で塗っておき、PSET で書き戻す。パターンの 1 の
;   ビットは色 7 で描かれ、0 のビットの点は色 3 のまま残る。
;
; @bas 21 LINE(100,100)-(163,163),PSET,7,B
; @bas 22 LINE(100,100)-(163,163),PSET,7
; @bas 23 LINE(108,140)-(155,159),PSET,7,BF
; @bas 24 LINE(300,100)-(363,163),PSET,3,BF
; @bas 25 DIM A%(300)
; @bas 26 GET@(100,100)-(163,163),A%,G
; @bas 27 PUT@(300,100)-(363,163),A%,PSET
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     1
        FCB     $00,$02,$0C,$16         ; カーソルを伏せる (制御コードの解釈は残す)

OBSTAB:
        FCB     OP_CNT,7
        FDB     100,100,163,163         ; 元の点の数
        FCB     OP_CNT,7
        FDB     300,100,363,163         ; 写しの点の数 (元と同じ)
        FCB     OP_CNT,7
        FDB     300,115,363,163         ; 写しの行 15〜63 (継続で送った部分を含む)
        FCB     OP_CNT,3
        FDB     300,100,363,163         ; 0 のビットの点は塗った色のまま
        FCB     OP_PROBE
        FDB     300,163                 ; 枠の左下
        FCB     OP_PROBE
        FDB     363,163                 ; 枠の右下
        FCB     OP_PROBE
        FDB     330,150                 ; 塗り潰し矩形の中
        FCB     OP_PROBE
        FDB     304,120                 ; 0 のビット
        FCB     OP_END
        END
