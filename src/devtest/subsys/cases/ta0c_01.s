; 対象: FM77AV 系 / サブシステム Type-A の位置の ROM
; ta0c_01 — RESET 直後のコンソール制御は CF=$23 (オート LF / オーダ動作 /
;   カーソル表示) である
;   本サンプルはサブシステムがリセットされた直後に走り、コンソール制御 ($0C) を
;   一度も発行せずに $03 で "A" CR "B" を出す。オート LF が効いていれば CR は
;   行送りも伴うので、"A" は 0 行目、"B" は 1 行目の先頭の桁に出る。効いて
;   いなければ "B" は "A" と同じ桁を上書きしてしまい、1 行目には何も出ない。
;   RESET 直後の書式は 80 桁 25 行なので 1 文字は 8x8 画素で、0 行目の先頭の桁は
;   (0,0)-(7,7)、1 行目の先頭の桁は (0,8)-(7,15) に当たる。
;   CF のカーソル表示 (bit0) も一緒に確かめられる。コンソール制御を発行していない
;   ので、出力を終えたサブシステムは CF の指定どおりにカーソルを出す。出力後の
;   カーソルは "B" の次の桁 (1 行目の 2 桁目 = (8,8)-(15,15)) にあり、そのセルは
;   反転して全画素が灯るので、1 行目の残りを数えると 1 セルぶんの 64 になる。
;   カーソル表示が落ちていれば 0 になる。
; 準備: 全画面を消去する ($02。コンソール制御には触れない)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     2
        FCB     $00,$01,$02
        FCB     $00,$05,$03,$03,$41,$0D,$42

OBSTAB:
        FCB     OP_ANY
        FDB     0,0,7,7                 ; 0 行目の先頭の桁 = "A"
        FCB     OP_ANY
        FDB     0,8,7,15                ; 1 行目の先頭の桁 = "B"
        FCB     OP_LIT
        FDB     8,0,639,15              ; 0・1 行目の残り: カーソルのセル 1 個 (64 画素) だけ
        FCB     OP_LIT
        FDB     0,16,639,199            ; 2 行目以降: 何も出ない
        FCB     OP_END
        END
