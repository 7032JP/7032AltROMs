; tc05_02 — $05 GETC: 変更フィールドが 2 つあるときの読込み (参考書籍)。
;   桁 0 と桁 2 に SF オーダでフィールドの先頭を定める。前のフィールドは桁 0-1、
;   後のフィールドは桁 2 以降になる。バッファアドレスを桁 0 へ戻して $04 を発行し、
;   オペレータが A B C D と打って [RETURN] で終結すると、2 つのフィールドが
;   どちらも変更フィールドになる。
;     $04 GET  … 画面最上段の変更フィールド (桁 0、TEXT = AB)
;     $05 GETC … 未転送の変更フィールド     (桁 2、TEXT = CD)
;     $05 GETC … 残りが無いので N = 0
;   打鍵は tc05_02.stdin から送る。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
;   行 15 で先行入力の許可 ($1B $67) を送ってキー入力の状態を明示する。キーバッファは
;   本コマンドを出すより先に届いた打鍵も押された順に保つので、打鍵の届く時刻に
;   結果が左右されない。
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
; @bas 15 PRINT CHR$(27)+CHR$(103);
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$0F,$03,$0D
        FCB     $12,$00,$00,$11,$07
        FCB     $12,$02,$00,$11,$07
        FCB     $12,$00,$00
        FCB     $07,$01,$04
        FCB     $07,$01,$05
        FCB     $02,$01,$05

OBSTAB:
        FCB     OP_END
        END
