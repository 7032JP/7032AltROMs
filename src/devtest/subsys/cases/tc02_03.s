; tc02_03 — $02 ERASE の範囲の外にカーソルがあるとき、カーソルの反転が画面に残らない
;   画面は $01 で 25 行のうち 10〜14 行をスクロールモード画面に定め、全画面を消す。
;   $0C でカーソルを出すと、スクロールモード画面の先頭のセルに反転が掛かる。
;   続けて W=2 (ページモード 1 画面 = 0〜9 行) を消し、$0C でカーソルを伏せる。
;   消した範囲はカーソルのセルを含まないが、伏せた後の画面には何も残らない。
; 準備: カーソルを伏せる ($0C・下位ビット 0)
;
; コマンドを発行し、画面を読み戻して照合する。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$00
        FCB     $00,$09,$01,$00,$50,$19,$0A,$05,$00,$01,$00
        FCB     $00,$03,$02,$00,$00
        FCB     $00,$02,$0C,$01
        FCB     $00,$03,$02,$02,$00
        FCB     $00,$02,$0C,$00

OBSTAB:
        FCB     OP_LIT
        FDB     0,0,639,199
        FCB     OP_END
        END
