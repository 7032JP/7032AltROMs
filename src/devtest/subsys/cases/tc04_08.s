; tc04_08 — $04 コンソール行入力: キー待ちの点滅を挟んでも、終結後のセルが元へ戻る
;   キーを待っている間、カーソルは 0.4 秒ごとにセルの反転を入れ替えて点滅する。
;   打鍵が届くまでの時間は一定ではないので、終結する時点で反転が掛かっているか
;   どうかも一定ではない。それでも終結後のセルは「カーソルを出す前の見え方」に
;   戻らなければならない (掛かっていれば外し、外れていればそのままにする)。
;   画面の先頭 (0,0) へ $07 で "A" を置き、表示制御でカーソルを出さない指定に
;   したまま $04 を発行して [RETURN] で終結させ、セルを読み戻す。
;   打鍵は tc04_08.stdin から送る (走り出してからしばらく後に届くので、
;   待っている間に点滅が何度も入る)。
;   字形の点の数や位置は ROM ごとに違うので、字形に頼らない所だけを見る。
;     セル (0,0)-(15,9)          … "A" が残っている (反転の外し方が過剰でない)
;     セルの下 2 ライン (0,8)-(15,9) … 字形の外。反転が残っていれば点が出る
;     それ以外の画面             … 何も出ない
; 準備: カーソルを出さない表示制御にし ($0C・下位ビット 0)、全画面を消去する ($02)
;
;   行 15 で先行入力の許可 ($1B $67) を送ってキー入力の状態を明示する。キーバッファは
;   本コマンドを出すより先に届いた打鍵も押された順に保つので、打鍵の届く時刻に
;   結果が左右されない。
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
; @bas 15 PRINT CHR$(27);CHR$(103);
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $00,$08,$07,$00,$00,$00,$00,$07,$01,$41
        FCB     $01,$01,$04

OBSTAB:
        FCB     OP_ANY
        FDB     0,0,15,9                ; "A" が残っている
        FCB     OP_LIT
        FDB     0,8,15,9                ; セルの下 2 ライン: 反転が残っていない
        FCB     OP_LIT
        FDB     16,0,639,9              ; 同じ行の残り: 何も出ない
        FCB     OP_LIT
        FDB     0,10,639,199            ; 2 行目以降: 何も出ない
        FCB     OP_END
        END
