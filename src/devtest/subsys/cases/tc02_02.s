; tc02_02 — $02 ERASE の消去範囲 W: 1 スクロールモード画面 / 2 ページモード 1 画面 /
;   3 ページモード 2 画面 の BC
;   $D383=W 消去範囲 / $D384=BC 背景色
;   画面は $01 で 25 行のうち 10〜14 行をスクロールモード画面に定め、その上
;   (0〜9 行) をページモード 1 画面、下 (15〜24 行) をページモード 2 画面とする。
;   まず W=0 で全画面を白 (7) にし、W=1 に青 (1)、W=2 に赤 (2)、W=3 に緑 (4) を
;   添えて消す。BC が背景色になるのは W=0 のときだけで、W=1〜3 は W=0 で定めた背景色
;   (白) で消すので、どの行も白のまま (動作観察。$0D ERASE 2 の BC と同じ扱い、
;   参考書籍)。25 行のとき 1 行は 8 ライン分なので、行 r は y=8r〜8r+7。
; 準備: カーソルの点滅を止める ($0C・下位ビット 0)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$00
        FCB     $00,$09,$01,$00,$50,$19,$0A,$05,$00,$01,$00
        FCB     $00,$03,$02,$00,$07
        FCB     $00,$03,$02,$01,$01
        FCB     $00,$03,$02,$02,$02
        FCB     $00,$03,$02,$03,$04

OBSTAB:
        FCB     OP_PROBE
        FDB     320,4                   ; 行 0  ページモード 1 画面
        FCB     OP_PROBE
        FDB     320,76                  ; 行 9  同上
        FCB     OP_PROBE
        FDB     320,84                  ; 行 10 スクロールモード画面
        FCB     OP_PROBE
        FDB     320,116                 ; 行 14 同上
        FCB     OP_PROBE
        FDB     320,124                 ; 行 15 ページモード 2 画面
        FCB     OP_PROBE
        FDB     320,196                 ; 行 24 同上
        FCB     OP_END
        END
