; tc03_04 — アトリビュート文字の R (bit3) による反転表示 (参考書籍)。
;   同じ文字 (X) を、桁 0 に通常のアトリビュート (赤 = $02)、桁 4 に R を立てた
;   アトリビュート (赤 + 反転 = $0A) で置く。R = 1 のセルは文字の色を反転して
;   表示するので、字形の部分が黒、地の部分が赤になる。
;   40 桁 20 行モードの 1 セルは横 16 画素・縦 10 画素 = 160 画素なので、
;   通常のセルの赤い画素数と反転したセルの赤い画素数を足すと、字形の点の数に
;   よらず 160 になる。桁 0〜4 の矩形 (桁 1〜3 は空) の赤い画素を数える。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     3
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$0E,$03,$0C
        FCB     $12,$00,$00
        FCB     $11,$02,$58
        FCB     $12,$04,$00
        FCB     $11,$0A,$58

OBSTAB:
        FCB     OP_ANYC,2
        FDB     0,0,15,9                ; 桁 0 = 通常表示 (字形が赤)
        FCB     OP_LIT
        FDB     16,0,63,9               ; 桁 1-3: 何も出ない
        FCB     OP_CNT,2
        FDB     0,0,79,9                ; 桁 0-4 の赤: 通常の字形 + 反転の地 = 160
        FCB     OP_END
        END
