; tc04_02 — $04 GET: 変更フィールドの返却形式 (参考書籍)。
;   画面の先頭 (0,0) に SF オーダでフィールドを定めてから $04 を発行し、
;   オペレータが A B C と打って [RETURN] で終結したときの応答を読み戻す。
;     相対 3 = K   終了キーコード ($00 = RETURN)
;     相対 4 = N   今回転送された変更フィールドのバイト数 (SBA + X + Y + TEXT)
;     相対 5 = SBA オーダコード ($12)
;     相対 6 = X   変更フィールドの先頭の桁
;     相対 7 = Y   同 行
;     相対 8〜    TEXT (制御コードを除く文字列)
;   打鍵は tc04_02.stdin から送る。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
;   行 15 で先行入力の許可 ($1B $67) を送ってキー入力の状態を明示する。キーバッファは
;   本コマンドを出すより先に届いた打鍵も押された順に保つので、打鍵の届く時刻に
;   結果が左右されない。
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
; @bas 15 PRINT CHR$(27)+CHR$(103);
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$07,$03,$05
        FCB     $12,$00,$00,$11,$07
        FCB     $08,$01,$04

; 入力を待つ試験では、画面全体の画素数を観測項目に置かない (入力中はカーソルが
; 出るので、数える値が実行のたびに変わってしまう)。ここで確かめたいのは応答の
; 形式なので R3 だけを観測する。
OBSTAB:
        FCB     OP_END
        END
