; tc04_04 — アトリビュート文字の P (bit4) による保護 (参考書籍)。
;   P = 1 のフィールドは「保護」であり、オペレータは内容を変更できない。
;   画面の先頭に SF オーダで保護のフィールド (アトリビュート $17 = P + 白) を
;   定めてから $04 を発行し、A B と打って [RETURN] を押しても変更フィールドは
;   生じない (相対 4 の N = 0)。続けて同じ位置を保護でないフィールド
;   (アトリビュート $07 = 白) に定め直して $04 を発行すると、同じ打ち方で
;   変更フィールドが返る (N = 5、TEXT = C D)。
;   打鍵は tc04_04.stdin から送る。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
;   行 15 で先行入力の許可 ($1B $67) を送ってキー入力の状態を明示する。キーバッファは
;   本コマンドを出すより先に届いた打鍵も押された順に保つので、打鍵の届く時刻に
;   結果が左右されない。
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
; @bas 15 PRINT CHR$(27)+CHR$(103);
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$07,$03,$05
        FCB     $12,$00,$00,$11,$17
        FCB     $02,$01,$04
        FCB     $00,$07,$03,$05
        FCB     $12,$00,$00,$11,$07
        FCB     $07,$01,$04

OBSTAB:
        FCB     OP_END
        END
