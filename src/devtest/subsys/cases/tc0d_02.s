; tc0d_02 — $0D ERASE 2 の範囲 W=1 (スクロールモード画面) と、BC が W=0 のときだけ
;   有効であること
;   $D383=W 範囲 / $D384=BC 背景色 (W=0 のときのみ有効) / $D385=FC 文字色
;   画面を $01 (消去指定あり) で色 2 の一面にし、続く $01 (消去指定なし) で背景色
;   だけを 5 に変える。その状態で $0D を W=1・BC=1 で発行すると、消えるのは
;   スクロールモード画面 (10〜14 行) だけで、消えた色は BC の 1 ではなく背景色の
;   5 になる。25 行のとき 1 行は 8 ライン分なので、行 r は y=8r〜8r+7 に当たる。
; 準備: カーソルの点滅を止める ($0C・下位ビット 0)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$02,$0C,$00
        FCB     $00,$09,$01,$02,$50,$19,$0A,$05,$00,$01,$00
        FCB     $00,$09,$01,$05,$50,$19,$0A,$05,$00,$00,$00
        FCB     $00,$04,$0D,$01,$01,$07

OBSTAB:
        FCB     OP_PROBE
        FDB     320,4                   ; 行 0  ページモード 1 画面 (消えない)
        FCB     OP_PROBE
        FDB     320,84                  ; 行 10 スクロールモード画面 (背景色 5)
        FCB     OP_PROBE
        FDB     320,116                 ; 行 14 同上
        FCB     OP_PROBE
        FDB     320,124                 ; 行 15 ページモード 2 画面 (消えない)
        FCB     OP_END
        END
