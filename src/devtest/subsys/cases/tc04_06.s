; tc04_06 — $04 GET: [DUP] は 1 行上の文字を次の TAB 停止位置まで複写する。
;   停止位置を桁 3 に置き、上の行を "AB\0C"、入力行を "xy\0Z" とする。
;   入力行の先頭で [DUP] を押すと桁 0〜2 だけが "AB\0" に置換され、停止位置
;   の桁 3 にある Z は残る。$06 で入力行の 4 セルを読み戻す。
;   打鍵は tc04_06.stdin から送る。SHIFT 補助移動は対象にしない。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム。
;
; 行 15 で先行入力の許可 ($1B $67) を送ってキー入力の状態を明示する。
; @bas 15 PRINT CHR$(27)+CHR$(103);
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$0B,$0B,$10,$00,$00,$00,$00,$00,$00,$00,$00,$00
        FCB     $00,$1B,$03,$19
        FCB     $12,$00,$00,$11,$07,$41,$42
        FCB     $12,$03,$00,$43
        FCB     $12,$00,$01,$11,$07,$78,$79
        FCB     $12,$03,$01,$5A
        FCB     $12,$00,$01
        FCB     $00,$01,$04
        FCB     $FF,$05,$06,$00,$01,$03,$01

OBSTAB:
        FCB     OP_END
        END
