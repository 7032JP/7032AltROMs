; tc04_05 — $04 GET: [INS] の挿入と、フィールド末尾まで Null が無いときの不作動。
;   桁 0 のフィールドを "AC"（後ろに Null あり）、桁 5 のフィールドを "WXYZ"
;   （桁 9 の次フィールドまで Null なし）として表示し、カーソルを桁 0 に置く。
;   [INS], B で前者は "BAC" になり、右へ 4 回進んで後者で Q を打っても "WXYZ" の
;   まま残る。$06 で桁 0〜8 を読み戻し、両方の条件を 1 本で照合する。
;   打鍵は tc04_05.stdin から送る。SHIFT 補助移動は対象にしない。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム。
;
; 行 15 で先行入力の許可 ($1B $67) を送ってキー入力の状態を明示する。
; @bas 15 PRINT CHR$(27)+CHR$(103);
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     5
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$1A,$03,$18
        FCB     $12,$00,$00,$11,$07,$41,$43
        FCB     $12,$05,$00,$11,$07,$57,$58,$59,$5A
        FCB     $12,$09,$00,$11,$07
        FCB     $12,$00,$00
        FCB     $00,$01,$04
        FCB     $FF,$05,$06,$00,$00,$08,$00

OBSTAB:
        FCB     OP_END
        END
