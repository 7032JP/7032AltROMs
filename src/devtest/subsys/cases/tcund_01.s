; tcund_01 — 表に割当てのないコマンドコードの通し掃引
;   $00 / $0E-$14 / $21-$28 / $2D-$3C を順に発行する。$00 以外はいずれも受理して
;   正常に終わり、画面には何も描かない (受理されずに残るとサブ CPU が停止する)。
;   $00 だけは取り上げられない。共有 RAM 相対 2 (COMMAND) は「コマンドが無い
;   状態」を 0 で表す (参考書籍の
;   応答データが相対 2 = 0 と定める) ので、0 を書いてもコマンドの提示にならない。
;   よって発行 34 件のうち受理は 33 件になる
; 準備: カーソルの点滅を止め ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

