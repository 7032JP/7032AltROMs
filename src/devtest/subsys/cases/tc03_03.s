; tc03_03 — SF (Start Field) オーダ $11。
;   40 桁の 1 行目に色の違う 4 つのフィールド (白・赤・緑・青) を置き、2 つ目の
;   フィールドの先頭から SF (黄) と 8 文字を出す。フィールドの範囲を越えた先の
;   文字は書き直されず、元の色のまま残ることを確かめる。
;   40 桁 20 行モードの 1 セルは横 16 画素・縦 10 画素。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
; コマンドを発行し、画面を読み戻して照合する。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$22,$03,$20
        FCB     $12,$00,$00
        FCB     $11,$07,$41,$42
        FCB     $11,$02,$43,$44,$45,$46,$47,$48
        FCB     $11,$04,$49,$4A,$4B,$4C,$4D,$4E
        FCB     $11,$01,$4F,$50,$51,$52,$53,$54,$55
        FCB     $00,$0F,$03,$0D
        FCB     $12,$02,$00
        FCB     $11,$06,$31,$32,$33,$34,$35,$36,$37,$38

OBSTAB:
        FCB     OP_ANYC,7
        FDB     0,0,31,9                ; A B (桁 0-1) は SF の外なので白のまま
        FCB     OP_ANYC,6
        FDB     32,0,159,9              ; 1〜8 (桁 2-9) は新しいアトリビュート = 黄で描かれる
        FCB     OP_CNT,2
        FDB     32,0,159,9              ; 同じ範囲に C〜H の赤は残らない
        FCB     OP_CNT,4
        FDB     32,0,159,9              ; 同じ範囲に I J の緑は残らない
        FCB     OP_ANYC,4
        FDB     160,0,223,9             ; K L M N (桁 10-13) は緑のまま
        FCB     OP_CNT,6
        FDB     160,0,223,9             ; 同じ範囲に黄の画素は無い (書き直されていない)
        FCB     OP_ANYC,1
        FDB     224,0,335,9             ; 次のフィールド O〜U (桁 14-20) は青のまま
        FCB     OP_END
        END
