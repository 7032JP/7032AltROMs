; tcbas_09 — スクロール領域の指定 (CONSOLE 文) と、その領域だけのスクロール
;   参考書籍の CONSOLE 文は、テキスト描画のうち「開始行から
;   何行ぶん」をスクロール領域にするかを指定します。以後の表示はその領域の中に
;   出て、領域の最下行から出るときは領域の中だけが 1 行スクロールします。
;
;   80 桁 x 20 行 (1 行 10 ライン) にしてから、16 行目から 4 行 (= 行 16-19、
;   y=160..199) をスクロール領域に定めます。CONSOLE は画面を消してカーソルを
;   領域の左上へ置くので、そのあと
;     - 行 15 (y=150..159) を色 7 で塗り潰す … 領域の 1 行上。動いてはならない
;     - 行 19 (y=190..199) を色 7 で塗り潰す … 領域の最下行。1 行上へ移るはず
;   としてから、空の表示を 4 回行います。カーソルは行 16 から 17・18・19 と
;   下がり、4 回目で領域の最下行から出るので領域が 1 行スクロールします。
;
;   スクロールの後は
;     行 15  … 塗り潰しのまま (6400 = 640 x 10 画素)。領域の外は動かない
;     行 16-17 … 空
;     行 18  … 塗り潰し (行 19 の内容が 1 行上へ移った)
;     行 19  … 空 (スクロールで新しくなった行は消される)
;   になります。カーソルは表示を消して (LOCATE の第 3 引数 0) 領域の左上に
;   置き、点滅の反転が観測に混じらないようにしています。
;
; @bas 21 WIDTH 80,20:CONSOLE 16,4:LOCATE 0,16,0
; @bas 22 LINE(0,150)-(639,159),PSET,7,BF
; @bas 23 LINE(0,190)-(639,199),PSET,7,BF
; @bas 24 PRINT:PRINT:PRINT:PRINT
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     1
        FCB     $00,$02,$0C,$16         ; カーソルを伏せる (制御コードの解釈は残す)

OBSTAB:
        FCB     OP_LIT
        FDB     0,0,639,149             ; 領域より上: 何も出ない
        FCB     OP_LIT
        FDB     0,150,639,159           ; 領域の 1 行上: 塗り潰しのまま (6400)
        FCB     OP_LIT
        FDB     0,160,639,179           ; 領域の 1-2 行目: 空
        FCB     OP_LIT
        FDB     0,180,639,189           ; 領域の 3 行目: 最下行の内容が移ってきた (6400)
        FCB     OP_LIT
        FDB     0,190,639,199           ; 領域の最下行: スクロールで消される
        FCB     OP_END
        END
