; tc0c_01 — $0C カーソル制御: bit0=1 でカーソルを出し、bit0=0 で伏せる
;   直前に $02 CLS でカーソルをホーム (0,0) へ戻し、そのセルへ $07 で "A" を置いてから
;   カーソルを出す。カーソルはセルの反転で見せるので、出している間その "A" は
;   反転して見え、伏せると元の字形へ戻る。
;   観測はカーソルを伏せた後に行う。表示指定が落ちている間は点滅が働かないため、
;   観測中に画面が変わることがない (出している間に何度点滅を挟んでも、伏せる側が
;   そのときの反転状態を見て外すので、結果は経過時間に左右されない)。
;   字形に依存しないよう、字形に頼らない所だけを見る。
;     セル (0,0)-(15,9) … "A" の点が残る。反転の外し方が過剰なら残らない
;     セルの下 2 ライン (0,8)-(15,9) … 字形の外。反転が残っていれば点が出る
;     それ以外の画面 … カーソルのセルの外は最初から最後まで何も出ない
; 準備: カーソルの点滅を止め ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     6
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $00,$01,$02
        FCB     $00,$08,$07,$00,$00,$00,$00,$07,$01,$41
        FCB     $00,$02,$0C,$03
        FCB     $00,$02,$0C,$00

OBSTAB:
        FCB     OP_ANY
        FDB     0,0,15,9                ; "A" が残っている (外し方が過剰でない)
        FCB     OP_LIT
        FDB     0,8,15,9                ; セルの下 2 ライン: 反転が残っていない
        FCB     OP_LIT
        FDB     16,0,639,9              ; 同じ行の残り: 何も出ない
        FCB     OP_LIT
        FDB     0,10,639,199            ; 2 行目以降: 何も出ない
        FCB     OP_END
        END
