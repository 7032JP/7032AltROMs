; tc03_11 — EL (Erase Line) オーダ $05 を図形の上で出したときの見え方。
;   EL はバッファアドレスからそのフィールドの終りまでを Null コード ($00) で
;   埋める (参考書籍)。画面の描き直しは、範囲の中で最後に Null でなかったセル
;   までに限り、その後ろの Null のままのセルは描かないので、その上の図形は残る。
;   画面の上 2 行 (縦 0-19) を色 6 の塗潰し矩形 ($15 形状 2) にしてから、
;   桁 0 から赤のフィールド (A B C D) を置き、桁 1 へ戻して EL を出す。
;   桁 1-3 (B C D) は Null として描き直されて消え、桁 4 から後ろと 2 行目の
;   図形は消えずに残る。桁 0 の A も残る。
;   40 桁 20 行モードの 1 セルは横 16 画素・縦 10 画素。
; 準備: $01 で 40 桁 20 行に初期化して消去し、制御コードを動作として扱う表示状態にする
;   ($0C・カーソルは消す)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$09,$01,$00,$28,$14,$00,$14,$00,$01,$00
        FCB     $00,$02,$0C,$16
        FCB     $00,$0C,$15,$06,$00,$00,$00,$00,$00,$02,$7F,$00
        FCB     $13,$02
        FCB     $00,$0F,$03,$0D
        FCB     $12,$00,$00
        FCB     $11,$02,$41,$42,$43,$44
        FCB     $12,$01,$00,$05

OBSTAB:
        FCB     OP_ANYC,2
        FDB     0,0,15,9                ; A (桁 0) は残る
        FCB     OP_LIT
        FDB     16,0,63,9               ; B C D (桁 1-3) は Null として描き直されて消えている
        FCB     OP_CNT,6
        FDB     64,0,639,9              ; 桁 4 から後ろの図形は残る (576 x 10)
        FCB     OP_CNT,6
        FDB     0,10,639,19             ; 2 行目の図形は残る (640 x 10)
        FCB     OP_END
        END
