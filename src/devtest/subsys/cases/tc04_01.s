; tc04_01 — $04 コンソール行入力: 表示する文字列なし (N=0) で入力を待ち、[RETURN] だけを
;   受けたときの応答 (相対 3 = 終了キーコード K = $00 (RETURN))
;   ($04 は入力が終結するまで待ち続けるコマンドで、この試験は打鍵 ([RETURN]) を
;    tc04_01.stdin から送って待ちを解く)
; 準備: カーソルの点滅を止め ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
;   行 15 で先行入力の許可 ($1B $67) を送ってキー入力の状態を明示する。キーバッファは
;   本コマンドを出すより先に届いた打鍵も押された順に保つので、打鍵の届く時刻に
;   結果が左右されない。
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
; @bas 15 PRINT CHR$(27);CHR$(103);
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     3
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $01,$01,$04

; 入力を待つ試験では、画面全体の画素数を観測項目に置かない (入力中はカーソルが
; 出るので、数える値が実行のたびに変わってしまう)。
; ここで確かめたいのは「[RETURN] で終結したときの応答」なので R2 だけを観測する。
OBSTAB:
        FCB     OP_END
        END
