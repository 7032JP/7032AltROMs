; tc20_01 — $20 文字ライン (直線): $D383=属性, $D384=文字コード,
;   $D386=X0, $D388=Y0, $D38A=X1, $D38C=Y1 (文字座標), $D38D=形状 (0=直線)
; 準備: カーソルの点滅を止め ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
; 画素の座標は文字セルの並びから決まります。40 桁 x 20 行 では 1 桁 16 画素・
;   1 行 10 画素なので、セル (0,0) は x=0..15 / y=0..9、セル (1,1) は
;   x=16..31 / y=10..19 です。対角のセルに `*` の点があり、それ以外のセルに
;   点が無いことを見ます (字形に依存しないよう、点の数や位置は見ません)。
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     3
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $00,$0C,$20,$07,$2A,$00,$00,$00,$00,$00,$04,$00
        FCB     $04,$00

OBSTAB:
        FCB     OP_ANYC,7
        FDB     0,0,15,9                ; セル (0,0)
        FCB     OP_ANYC,7
        FDB     16,10,31,19             ; セル (1,1)
        FCB     OP_ANYC,7
        FDB     64,40,79,49             ; セル (4,4)
        FCB     OP_LIT
        FDB     16,0,639,9              ; 0 行目の残り: 何も出ない
        FCB     OP_LIT
        FDB     0,10,15,19              ; セル (0,1): 何も出ない
        FCB     OP_LIT
        FDB     0,50,639,199            ; 5 行目以降: 何も出ない
        FCB     OP_END
        END
