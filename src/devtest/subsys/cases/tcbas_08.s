; tcbas_08 — 起動直後のテキスト書式 (40 桁 x 20 行) と文字セルの塗り替え
;   参考書籍の WIDTH は 40 桁の標準画面を 20 行として説明して
;   います。200 ライン / 20 行 = 1 行 10 ライン なので、行 1 のセルは y=10..19、
;   行 0 のセルは y=0..9 に当たります。40 桁は 1 桁 16 画素なので、桁 0 は
;   x=0..15、桁 2 は x=32..47 です。
;
;   画面全体を色 7 で塗り潰してから、行 1 桁 0 へ空白を 1 文字書きます。
;     - 書いたセル (x=0..15, y=10..19) は 10 ライン全部が消えること
;       (字形は 8 ライン ぶんなので、下端 2 ラインが残らないことの確認)
;     - 行 0 のセル (x=0..15, y=0..9) は無傷であること
;       (= 行 1 が y=10 から始まる。1 行 8 ライン なら行 1 は y=8 から始まり、
;          この区画の下 2 ラインが消えてしまう)
;     - 隣の桁 (x=32..47, y=10..19) は無傷であること
;   BASIC の描画文と表示文で画面を作り、その結果をこのサンプル自身が読み戻して
;   報告します。先頭の `@bas` 行が、機械語を読み込んだあとに走らせる BASIC の行です。
;
; @bas 21 LINE(0,0)-(639,199),PSET,7,BF
; @bas 22 LOCATE 0,1
; @bas 23 PRINT " ";
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     1
        FCB     $00,$02,$0C,$16         ; カーソルを伏せる (制御コードの解釈は残す)

OBSTAB:
        FCB     OP_LIT
        FDB     0,10,15,19              ; 書いたセル: 10 ライン全部が消える
        FCB     OP_CNT,7
        FDB     0,0,15,9                ; 行 0 のセル: 無傷 (16 x 10 = 160)
        FCB     OP_CNT,7
        FDB     32,10,47,19             ; 隣の桁: 無傷 (16 x 10 = 160)
        FCB     OP_END
        END
