; tc03_12 — EL (Erase Line) オーダ $05 で Null になった反転表示のセルの見え方
;   (単色表示・20 行モード)。
;   $01 で 40 桁 20 行・単色表示 (GR = 1) に初期化し、桁 0 から R (bit3) を
;   立てた赤のフィールド ($11 $0A、A B C D) を置き、桁 1 へ戻して EL を出す。
;   アトリビュートの R が 1 のセルは文字の色を反転して表示し (参考書籍)、
;   単色表示では文字を緑だけで表示する (参考書籍)。Null のセルの字形には点が
;   無いので、反転した桁 1-3 は地の全体が緑になる。1 セルは横 16 画素・縦 10 画素
;   なので、桁 1-3 の緑は字形によらず 3 x 160 = 480 (下端の 2 ラインを含む)。
; 準備: $01 で消去と初期化を行い、制御コードを動作として扱う表示状態にする ($0C・カーソルは消す)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     3
        FCB     $00,$09,$01,$00,$28,$14,$00,$14,$00,$01,$01
        FCB     $00,$02,$0C,$16
        FCB     $00,$0F,$03,$0D
        FCB     $12,$00,$00
        FCB     $11,$0A,$41,$42,$43,$44
        FCB     $12,$01,$00,$05

OBSTAB:
        FCB     OP_CNT,4
        FDB     16,0,63,9               ; 桁 1-3: 反転した Null のセルは緑の一面 (480)
        FCB     OP_LIT
        FDB     16,0,63,9               ; 桁 1-3: 緑のほかの色は無い (480)
        FCB     OP_CNT,2
        FDB     0,0,63,9                ; 単色表示なので赤の画素は無い
        FCB     OP_ANYC,4
        FDB     0,0,15,9                ; 桁 0 の A (反転) も緑で出る
        FCB     OP_LIT
        FDB     64,0,639,19             ; 桁 4 から後ろと 2 行目には何も無い
        FCB     OP_END
        END
