; tc0c_02 — $0C カーソル制御: 行入力の外ではカーソルが点滅しない
;   カーソルの点滅は行入力 ($04) がキーを待っている間だけ働く。それ以外の間は、
;   出したカーソルの反転がそのまま留まる。
;   $02 でカーソルをホーム (0,0) へ戻し、そのセルへ $07 で "A" を置いてから
;   $0C でカーソルを出し、出したまま観測する。
;   観測はカーソルのセルの下 2 ライン (字形の外) に反転が残っているかを、
;   画面全体の読み戻しを挟んで 2 回行う。読み戻しには点滅の周期 (0.4 秒ごとに
;   反転を入れ替える) より長い時間がかかるので、行入力の外でも点滅していれば
;   2 回の観測の結果が食い違う。
;   字形に依存しないよう、字形に頼らない所だけを見る。
;     セルの下 2 ライン (0,8)-(15,9) … 反転が掛かっていれば点が出る
;     それ以外の画面 … カーソルのセルの外は最初から最後まで何も出ない
; 準備: カーソルを伏せ ($0C・下位ビット 0)、全画面を消去する ($02・全画面/黒)
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     5
        FCB     $00,$02,$0C,$00
        FCB     $00,$01,$02
        FCB     $00,$01,$02
        FCB     $00,$08,$07,$00,$00,$00,$00,$07,$01,$41
        FCB     $00,$02,$0C,$03

OBSTAB:
        FCB     OP_ANY
        FDB     0,8,15,9                ; 反転が掛かっている
        FCB     OP_LIT
        FDB     16,0,639,9              ; 同じ行の残り: 何も出ない
        FCB     OP_LIT
        FDB     0,10,639,199            ; 2 行目以降: 何も出ない
        FCB     OP_ANY
        FDB     0,8,15,9                ; 時間が経っても反転のまま (点滅していない)
        FCB     OP_END
        END
