; tc03_05 — EL (Erase Line) オーダ $05 のフィールド境界 (参考書籍)。
;   EL は「現在のバッファアドレスから、そのフィールドの終りまでを Null コード
;   ($00) で埋め」る。桁 0 から赤のフィールド (A B C D)、桁 4 から緑のフィールド
;   (E F G H) を置き、桁 2 へ戻して EL を出す。消えるのは C D (桁 2-3) だけで、
;   A B と、次のフィールドの E F G H は残る。
;   40 桁 20 行モードの 1 セルは横 16 画素・縦 10 画素。
; 準備: 制御コードを動作として扱う表示状態にし ($0C・カーソルは消す)、$02 で消去+ホーム
;
; このサンプル自身がコマンドを発行し、応答と表示結果を読み戻します。
        INCLUDE "subsysrt.inc"

CMDTAB:
        FCB     4
        FCB     $00,$02,$0C,$16
        FCB     $00,$01,$02
        FCB     $00,$11,$03,$0F
        FCB     $12,$00,$00
        FCB     $11,$02,$41,$42,$43,$44
        FCB     $11,$04,$45,$46,$47,$48
        FCB     $00,$06,$03,$04
        FCB     $12,$02,$00,$05

OBSTAB:
        FCB     OP_ANYC,2
        FDB     0,0,31,9                ; A B (桁 0-1) は残る
        FCB     OP_CNT,2
        FDB     32,0,63,9               ; C D (桁 2-3) はフィールドの終りまで消えている
        FCB     OP_ANYC,4
        FDB     64,0,127,9              ; 次のフィールド E F G H (桁 4-7) は消えない
        FCB     OP_END
        END
