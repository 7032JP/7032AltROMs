; AltROMs extsub.rom — FM77AV40EX / AV40SX 拡張サブシステム ROM (枠 + フォント部)
;
; 49152 byte 固定 (ビルド時に検証)。
;
; 全体構成:
;   24KB の拡張サブシステムイメージ 2 セットからなる。
;   各セットの内訳は CGRAM 用 16KB (2KB x 8 バンク) + 実行ページ用 8KB。
;
;   +---------------------------------------------------------------+
;   | セット 1  $0000-$5FFF (24KB)                                   |
;   |   CGRAM  $0000-$3FFF (2KB x 8 バンク)                          |
;   |   実行   $4000-$5FFF (8KB)                                     |
;   +---------------------------------------------------------------+
;   | セット 2  $6000-$BFFF (24KB)                                   |
;   |   CGRAM  $6000-$9FFF (2KB x 8 バンク)                          |
;   |   実行   $A000-$BFFF (8KB)                                     |
;   +---------------------------------------------------------------+
;
; 本バージョンの実装範囲:
;   - フォント部 (CGRAM に供給する ANK 字形) を実装する。
;   - 機能部 (拡張サブシステムのプログラム本体) は未実装 (ゼロ埋め)。
;
; フォント字形:
;   8x8 ANK (2KB) は scripts/genfont.py が生成する。
;   8x16 ANK は scripts/genfont16.py が上記 8x8 を縦 2 倍に引き伸ばして生成する
;   (4KB)。
;
; 仕様根拠: サイズ・領域構成は参考書籍および動作観察に基づく。
;==============================================================================

                ORG     $0000

;==============================================================================
; セット 1 : $0000-$5FFF (24KB)
;==============================================================================

;------------------------------------------------------------------------------
; CGRAM バンク 0-1 : $0000-$0FFF — 8x16 ANK フォント 256 字 (4KB)
;   1 文字 16 byte。2KB バンク 2 本にまたがって連続配置される。
;------------------------------------------------------------------------------
s1_ank16:       INCLUDEBIN "../build/font16.bin"
                ZMB     $1000-*

;------------------------------------------------------------------------------
; CGRAM バンク 2 : $1000-$17FF — 8x8 ANK フォント 256 字 (2KB)
;   1 文字 8 byte。
;------------------------------------------------------------------------------
s1_ank8:        INCLUDEBIN "../build/font.bin"
                ZMB     $1800-*

;------------------------------------------------------------------------------
; CGRAM バンク 3-7 : $1800-$3FFF — 予約 (未実装。ゼロ埋め)
;   拡張文字セット等の枠。本バージョンでは字形を持たない。
;------------------------------------------------------------------------------
                ZMB     $4000-*

;------------------------------------------------------------------------------
; 実行ページ : $4000-$5FFF (8KB) — プレースホルダ (未実装。ゼロ埋め)
;   未実装 (ゼロ埋め)。
;------------------------------------------------------------------------------
                ZMB     $6000-*

;==============================================================================
; セット 2 : $6000-$BFFF (24KB)
;==============================================================================

;------------------------------------------------------------------------------
; CGRAM バンク 0 : $6000-$67FF — 8x8 ANK フォント 256 字 (2KB)
;   セット 1 の 8x8 と同一字形。
;------------------------------------------------------------------------------
s2_ank8:        INCLUDEBIN "../build/font.bin"
                ZMB     $6800-*

;------------------------------------------------------------------------------
; CGRAM バンク 1 : $6800-$6FFF — 8x8 ANK フォント 256 字 (2KB、別書体枠)
;   8x8 と同じ字形。
;------------------------------------------------------------------------------
s2_ank8_alt:    INCLUDEBIN "../build/font.bin"
                ZMB     $7000-*

;------------------------------------------------------------------------------
; CGRAM バンク 2-7 : $7000-$9FFF — 予約 (未実装。ゼロ埋め)
;------------------------------------------------------------------------------
                ZMB     $A000-*

;------------------------------------------------------------------------------
; 実行ページ : $A000-$BFFF (8KB) — プレースホルダ (未実装。ゼロ埋め)
;------------------------------------------------------------------------------
                ZMB     $C000-*         ; 全体を 49152 byte に揃える
