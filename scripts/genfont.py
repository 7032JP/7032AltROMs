CTRL_NAMES = [
    None, "SH", "SX", "EX", "ET", "EQ", "AK", "BL",     # $00-$07
    "BS", "HT", "LF", "VT", "FF", "CR", "SO", "SI",     # $08-$0F
    "DL", "D1", "D2", "D3", "D4", "NK", "SY", "EB",     # $10-$17
    "CN", "EM", "SB", "EC", "FS", "GS", "RS", "US",     # $18-$1F
]


def ctrl_glyph(name):
    """略号 2 文字を左上 (行 0-3, 列 0-2) と右下 (行 4-7, 列 4-6) へ置く。"""
    rows = [0] * 8
    for k, ch in enumerate(name):
        pat = MINI[ch]
        top = 0 if k == 0 else 4          # 行の起点
        shift = 5 if k == 0 else 1        # 列 0-2 / 列 4-6 (bit7-5 / bit3-1)
        for y, r in enumerate(pat):
            v = 0
            for i, c in enumerate(r):
                if c == "#":
                    v |= 0x04 >> i
            rows[top + y] |= v << shift
    return rows


def control_pictograms():
    return {code: ctrl_glyph(nm)
            for code, nm in enumerate(CTRL_NAMES) if nm is not None}


# --- 半グラフィック $80-$9F (アルゴリズム生成) ----------------------------

def bar_bottom(n):
    """下詰めバーグラフ: 下から n/8 を全幅で埋める (n=1..8)。"""
    return [0x00] * (8 - n) + [0xFF] * n


def bar_left(n):
    """左詰めバーグラフ: 左から n/8 列を全高で埋める (n=1..7)。"""
    v = (0xFF00 >> n) & 0xFF
    return [v] * 8


def box_line(up=False, down=False, left=False, right=False):
    """罫線パーツ: 中心 (列 4 / 行 4) から各方向へ 1px 線を伸ばす。"""
    rows = [0] * 8
    if up:
        for y in range(0, 5):
            rows[y] |= 0x08  # 列 4 (= bit3)
    if down:
        for y in range(4, 8):
            rows[y] |= 0x08
    h = 0
    if left:
        h |= 0xF8  # 列 0-4
    if right:
        h |= 0x0F  # 列 4-7
    rows[4] |= h
    return rows


def semigraphics():
    sg = {}
    for n in range(8):                      # $80-$87: 下詰めバー 1/8〜8/8
        sg[0x80 + n] = bar_bottom(n + 1)
    for n in range(7):                      # $88-$8E: 左詰めバー 1/8〜7/8
        sg[0x88 + n] = bar_left(n + 1)
    T, F = True, False
    sg[0x8F] = box_line(T, T, T, T)         # 十字
    sg[0x90] = box_line(F, F, T, T)         # 横線
    sg[0x91] = box_line(T, T, F, F)         # 縦線
    sg[0x92] = box_line(F, T, F, T)         # コーナー 左上
    sg[0x93] = box_line(F, T, T, F)         # コーナー 右上
    sg[0x94] = box_line(T, F, F, T)         # コーナー 左下
    sg[0x95] = box_line(T, F, T, F)         # コーナー 右下
    sg[0x96] = box_line(T, T, F, T)         # T 字 右向き
    sg[0x97] = box_line(T, T, T, F)         # T 字 左向き
    sg[0x98] = box_line(F, T, T, T)         # T 字 下向き
    sg[0x99] = box_line(T, F, T, T)         # T 字 上向き
    sg[0x9A] = box_line(F, F, T, F)         # 半線 左
    sg[0x9B] = box_line(F, F, F, T)         # 半線 右
    sg[0x9C] = box_line(T, F, F, F)         # 半線 上
    sg[0x9D] = box_line(F, T, F, F)         # 半線 下
    sg[0x9E] = [0x80 >> y for y in range(8)]   # 斜線 (左上から右下)
    sg[0x9F] = [0xAA, 0x55] * 4                # 市松 50%
    return sg


# --- 品質ゲート -----------------------------------------------------------

def run_length_stats(data, lo=0x21, hi=0x7F):
    """水平方向の連続ドット (ラン) 長を収集し、1px ラン比率を返す。"""
    runs = []
    for code in range(lo, hi):
        for y in range(8):
            b = data[code * 8 + y]
            run = 0
            for bit in range(7, -1, -1):
                if (b >> bit) & 1:
                    run += 1
                elif run:
                    runs.append(run)
                    run = 0
            if run:
                runs.append(run)
    ones = sum(1 for r in runs if r == 1)
    return (ones / len(runs) if runs else 0.0), len(runs), ones


def main(out_path: str) -> None:
    data = bytearray(2048)  # 256 * 8 = 2048 byte
    tables = {}
    tables.update(control_pictograms())
    tables.update(GLYPHS)
    tables.update(semigraphics())
    tables.update(KANA)
    tables.update(GRAPHIC)
    for code, glyph in tables.items():
        check(len(glyph) == 8, f"glyph 0x{code:02X} must be 8 bytes")
        offset = code * 8
        for i, b in enumerate(glyph):
            data[offset + i] = b

    # ゲート 1: サイズ固定 (ROM アンカー保護)
    check(len(data) == 2048, "font.bin must be 2048 bytes")
    # ゲート 2: $87 = 全面ブロック (FF x8)
    check(bytes(data[0x87 * 8:0x87 * 8 + 8]) == b"\xFF" * 8, "$87 must be full block")
    # ゲート 3: グラフィックパターンの種数
    #   グラフィックの区画は $80-$9F と $E0-$FF の 64 コードで、
    #   そのうち全面ブロックと市松の 2 模様が両区画に重なるので 62 種になる。
    graphic_codes = list(range(0x80, 0xA0)) + list(range(0xE0, 0x100))
    patterns = {bytes(data[c * 8:c * 8 + 8]) for c in graphic_codes}
    check(
        bytes(8) not in patterns,
        "グラフィックの区画 ($80-$9F / $E0-$FF) に字形の無い符号位置があります",
    )
    check(
        len(patterns) == 62,
        f"グラフィックパターンの種数が {len(patterns)} 種 (62 種を期待)",
    )
    # ゲート 4: 1px ストローク比率 (太字リグレッション防止)
    ratio, total, ones = run_length_stats(data)
    check(
        ratio >= 0.60,
        f"1px run ratio {ratio:.1%} < 60% ({ones}/{total}) — 字形が太すぎます",
    )

    with open(out_path, "wb") as f:
        f.write(bytes(data))
    print(f"[OK] {out_path}: {len(data)} byte ({len(tables)} glyphs defined, "
          f"1px run ratio {ratio:.1%} = {ones}/{total})")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("usage: genfont.py <output.bin>", file=sys.stderr)
        sys.exit(1)
    main(sys.argv[1])
