"""
AltROMs 8x8 ANK フォント生成ツール。

256 文字 × 8 byte = 2048 byte の raw バイナリを出力。
LWASM の INCLUDEBIN で取り込まれ、subsys_c ROM の $D800-$DFFF に配置される。

文字配置:
  $00     : ゼロ埋め (表示状態が字形側でも空白 1 桁ぶんとして進む)
  $01-$1F : 制御コード絵文字 (略号 2 文字を斜めに配した 8x8)
  $20-$7E : ASCII 印字可能文字 (1px ストローク・7x7 ボックスで書き起こし)
  $7F     : ゼロ埋め
  $80-$87 : 下詰めバーグラフ 1/8〜8/8 ($87 = 全面ブロック FF x8)
  $88-$8E : 左詰めバーグラフ 1/8〜7/8
  $8F-$9F : 罫線パーツ (十字/縦横線/コーナー/T 字/半線/斜線/市松)
  $A1-$DF : JIS X 0201 片仮名・句読点
  $E0-$FF : グラフィック文字 (トランプ記号・丸・省略記号・市松/三角/×・罫線)

書体設計:
  - 縦線・横線とも 1px ストローク (セリフなし)。曲線は 1px 階段。
  - ASCII は 5 ドット幅をビット 6-2 へ配置、行 0-6 (行 7 はディセンダ専用)。
  - 片仮名は 7 ドット幅をビット 7-1 へ配置。
  - 字形は本スクリプトのドットパターン定義による本プロジェクトの設計。
  - 品質ゲート: $21-$7E の水平ラン長分布で 1px ラン比率 60% 以上を検査 (満たさなければ
    GlyphError を送出して生成を中止する。python -O でも無効化されない)。
"""

import sys


class GlyphError(ValueError):
    """字形定義または生成物が検査条件を満たさないときに送出する。"""


def check(cond: bool, msg: str) -> None:
    """検査条件が偽なら GlyphError を送出する。

    組込みの assert 文は python -O で無効化されるため、生成物の品質検査は
    必ず本関数 (= 常に効く例外送出) を通す。
    """
    if not cond:
        raise GlyphError(msg)


def g(*rows):
    """'.'/'#' の行 (最大 8 行、各行 8 桁まで・右側の '.' は省略可) を 8 byte 化。"""
    check(len(rows) <= 8, "max 8 rows")
    out = []
    for r in rows:
        check(len(r) <= 8, f"row too wide: {r!r}")
        v = 0
        for i, ch in enumerate(r):
            check(ch in ".#", f"bad char in row: {r!r}")
            if ch == "#":
                v |= 0x80 >> i
        out.append(v)
    while len(out) < 8:
        out.append(0)
    return out


def a(*rows):
    """ASCII 用: 5 ドット幅デザインをビット 6-2 へ配置 (左 1px 右 2px マージン)。"""
    return g(*["." + r for r in rows])


