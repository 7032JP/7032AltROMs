# --------------------------------------------------------------------------
# 差し替え字形表 (符号位置 -> 16 個の 16bit 値)
# --------------------------------------------------------------------------

OVERRIDES: dict[int, list[int]] = {}
for _part in (_KU1, _KU2, _KU567, _KU8):
    for _code, _rows in _part.items():
        check(_code not in OVERRIDES, f"符号位置が重複しています: {_code:04x}")
        OVERRIDES[_code] = _rows

# 定義の自己検査 (import 時に必ず効く)。
check(len(OVERRIDES) == 107,
      f"差し替え字形は 107 字でなければならない (現在 {len(OVERRIDES)} 字)")
for _code, _rows in OVERRIDES.items():
    check(0x2121 <= _code <= 0x2840,
          f"差し替えの対象は 1〜8 区のみ: {_code:04x}")
    check(len(_rows) == GLYPH_ROWS,
          f"{_code:04x}: 走査線が {len(_rows)} 本 ({GLYPH_ROWS} 本を期待)")
    check(all(0 <= _v <= 0xFFFF for _v in _rows),
          f"{_code:04x}: 走査線の値が 16bit を超えています")
    check(any(_rows), f"{_code:04x}: 字形が空白です")

_COUNT_BY_KU = {}
for _code in OVERRIDES:
    _COUNT_BY_KU[(_code >> 8) - 0x20] = _COUNT_BY_KU.get((_code >> 8) - 0x20, 0) + 1
check(_COUNT_BY_KU == {1: 47, 2: 25, 5: 1, 6: 1, 7: 1, 8: 32},
      f"区ごとの字数が想定と異なります: {_COUNT_BY_KU}")

del _part, _code, _rows


def kuten(code: int) -> tuple[int, int]:
    """JIS 符号値を (区, 点) へ分解する。"""
    return ((code >> 8) - 0x20, (code & 0xFF) - 0x20)


def render(code: int) -> str:
    """字形を '.'/'#' の 16 行文字列で返す (確認・資料作成用)。"""
    rows = OVERRIDES[code]
    return "\n".join(
        "".join("#" if r & (0x8000 >> c) else "." for c in range(GLYPH_COLS))
        for r in rows
    )


if __name__ == "__main__":
    for _c in sorted(OVERRIDES):
        _ku, _ten = kuten(_c)
        print(f"--- {_c:04x} ({_ku} 区 {_ten} 点) ---")
        print(render(_c))
