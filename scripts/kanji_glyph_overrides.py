"""
AltROMs 16x16 漢字フォント ROM 差し替え字形表。

JIS X 0208 の 1〜8 区にある 107 符号位置について、本プロジェクトが設計した
16x16 の字形を定義する。scripts/genkanji.py は ROM を組み立てる
段でこの表を読み、この 107 符号位置の字形を必ずここのものにする。同梱の入力
BDF (fonts/shinonome/shnmk16.bdf) は scripts/strip_bdf_chars.py で当該 107
符号位置の CHAR レコードを取り除いて改変したものであり、この 107 字の字形の供給元は
本表だけである。

位置づけと対象符号位置の一覧は docs/LEGAL.md §9.2 を参照。

字形の設計方針:

  - 枠は 16x16。走査線 0 が上端、桁 0 が左端 (bit15 が左端)。
  - 枠の幾何中心は走査線 7-8 の間・桁 7-8 の間にある。中心を通す線は
    2 dot 幅 (走査線 7-8 / 桁 7-8) を基本の太さとする。
  - 記号・数学記号・括弧は縦横とも 2 dot ストロークを基本とし、上下左右に
    1 dot 以上の余白を取る。囲み記号 (【】) だけは 3 dot ストロークとし、
    塗り記号 (●■◆★) との重さの釣り合いを取る。
  - 罫線素片 (8 区) と、隣の枠へ線をつなぐ全角記号 (― ｜) は、8x8 ANK
    フォント (scripts/genfont.py の box_line()) の罫線パーツと同じ軸に置く。
    ANK 側は 8 dot の枠で行 4 / 列 4 に 1 dot 線を引くので、これを縦横 2 倍に
    引き伸ばした走査線 8-9 / 桁 8-9 の 2 dot を細線とする (8x16 ANK フォントを
    8x8 から 2 倍に起こすのと同じ考え方)。太線は細線の両側へ 1 dot ずつ広げた
    4 dot (走査線 7-10 / 桁 7-10) とし、細線と同じ軸に載せる。腕は枠の縁まで
    引き、交点では細腕の始点を太幹の縁に合わせて段差が出ないようにする。
  - 数学記号 (− ＝ ÷ ≠ ≡ など) は罫線とは役割が違うので、枠の幾何中心
    (走査線 7-8) を数式軸として左右対称に組む。
  - 全角の対の記号 (開き括弧・引用符) は、開き側を枠の右寄り、閉じ側を枠の
    左寄りに置き、前後の字と間が空きすぎないようにする。
  - 句読点・小書きの点は 3〜4 dot 角の塊とし、ANK フォント側の点よりも
    一回り大きくして 16 dot の枠に負けない濃さにする。

字形の定義方法:

  - k() … '.'（消灯）と '#'（点灯）の行文字列で 1 字を書き起こす。行は最大
    16 行、各行は最大 16 桁で、右側と下側の省略は消灯として補う。
  - rule() … 罫線素片を「上下左右それぞれの腕の太さ」から機械的に組み立てる。
    32 字を同じ規則から導くことで、線幅・接続位置を全字でそろえる。
"""

from __future__ import annotations

GLYPH_ROWS = 16
GLYPH_COLS = 16

# 罫線の腕の太さ (走査線・桁の範囲)。8x8 ANK 罫線 (行 4 / 列 4 に 1 dot) を
# 縦横 2 倍に引き伸ばした 2 dot を細線とし、その両側へ 1 dot ずつ広げて太線とする。
LIGHT = (8, 9)
HEAVY = (7, 10)


class OverrideError(ValueError):
    """差し替え字形表が検査条件を満たさないときに送出する。"""


def check(cond: bool, msg: str) -> None:
    """検査条件が偽なら OverrideError を送出する。

    組込みの assert 文は python -O で無効化されるため、字形定義の検査は
    必ず本関数 (= 常に効く例外送出) を通す。
    """
    if not cond:
        raise OverrideError(msg)


def k(*rows: str) -> list[int]:
    """'.'/'#' の行 (最大 16 行・各行 16 桁まで) を 16 個の 16bit 値へ変換する。"""
    check(len(rows) <= GLYPH_ROWS, f"行が多すぎます: {len(rows)}")
    out: list[int] = []
    for r in rows:
        check(len(r) <= GLYPH_COLS, f"行が長すぎます: {r!r}")
        v = 0
        for i, ch in enumerate(r):
            check(ch in ".#", f"行に使えない文字があります: {r!r}")
            if ch == "#":
                v |= 0x8000 >> i
        out.append(v)
    while len(out) < GLYPH_ROWS:
        out.append(0)
    return out


def rule(up: int, down: int, left: int, right: int) -> list[int]:
    """罫線素片を組み立てる。各引数は腕の太さ (0=なし / 1=細線 / 2=太線)。

    腕は枠の縁まで引き、隣接する枠の同じ太さの腕と段差なくつながるようにする。
    交点では、細い腕の始点を太い幹の縁に合わせて空きが出ないようにする。
    """
    for w in (up, down, left, right):
        check(w in (0, 1, 2), f"腕の太さは 0/1/2 のいずれか: {w}")
    check(any((up, down, left, right)), "腕が 1 本もありません")

    def band(w: int) -> tuple[int, int]:
        return LIGHT if w == 1 else HEAVY

    vbands = [band(w) for w in (up, down) if w]
    hbands = [band(w) for w in (left, right) if w]
    vlo = min((b[0] for b in vbands), default=LIGHT[0])
    vhi = max((b[1] for b in vbands), default=LIGHT[1])
    hlo = min((b[0] for b in hbands), default=LIGHT[0])
    hhi = max((b[1] for b in hbands), default=LIGHT[1])

    cells: set[tuple[int, int]] = set()
    if left:
        lo, hi = band(left)
        cells |= {(r, c) for r in range(lo, hi + 1) for c in range(0, vhi + 1)}
    if right:
        lo, hi = band(right)
        cells |= {(r, c) for r in range(lo, hi + 1) for c in range(vlo, GLYPH_COLS)}
    if up:
        lo, hi = band(up)
        cells |= {(r, c) for c in range(lo, hi + 1) for r in range(0, hhi + 1)}
    if down:
        lo, hi = band(down)
        cells |= {(r, c) for c in range(lo, hi + 1) for r in range(hlo, GLYPH_ROWS)}

    out = [0] * GLYPH_ROWS
    for r, c in cells:
        out[r] |= 0x8000 >> c
    return out


